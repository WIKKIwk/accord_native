export function adminProgressQrInputScan(value: string, start: number, end: number, state: number, indices: number[]): number {
  for (let i = start; i < end; i++) {
    let char = value.charCodeAt(i) ^ 96; if (char > 95) char = 31;
    const transition = transitions.charCodeAt(state * 96 + char); state = transition & 31; indices[transition >> 5] = i;
  }
  return state;
}
