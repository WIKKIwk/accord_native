/**
 * Prototype contract only. A production implementation must make acquisition,
 * readback and owner-conditional release durable and linearizable across app
 * processes and restarts. Ordinary getItem/setItem pairs do not satisfy it.
 */
export type AssignmentWriteMarker = Readonly<{ version: 1; owner: string }>;
export type AtomicAssignmentHoldStore = {
  acquireIfAbsent(marker: AssignmentWriteMarker): Promise<boolean>;
  read(): Promise<AssignmentWriteMarker | null>;
  releaseIfOwner(owner: string): Promise<boolean>;
};
export class AssignmentWriteHoldError extends Error {
  constructor(readonly code: 'disabled' | 'not_current' | 'busy' | 'storage_uncertain' | 'ownership_uncertain' |
    'invalid_owner' | 'already_attempted', message: string) { super(message); }
}
const denied = (code: AssignmentWriteHoldError['code']) => new AssignmentWriteHoldError(code, 'Oldingi amal holati aniq emas. Yuborish bloklandi.');

/** An independently reviewed evaluator must reject async or malformed callbacks and consume their rejections. */
export type AssignmentHoldEvaluator = {
  isTrue(check: () => unknown): boolean;
  string(check: () => unknown): string | null;
};
function consumeUnexpected(value: unknown): void {
  if (value !== null && (typeof value === 'object' || typeof value === 'function')) void Promise.resolve(value).catch(() => {});
}
function trueResult(evaluator: AssignmentHoldEvaluator, check: () => unknown): boolean {
  try { const value: unknown = evaluator.isTrue(check); if (value !== true) consumeUnexpected(value); return value === true; }
  catch { return false; }
}
function stringResult(evaluator: AssignmentHoldEvaluator, check: () => unknown): string | null {
  try {
    const value: unknown = evaluator.string(check);
    if (typeof value === 'string' && value.length > 0) return value;
    consumeUnexpected(value); return null;
  } catch { return null; }
}

type HoldOptions = {
  /** This prototype is disabled unless an integrator explicitly opts in. */
  enabled?: boolean;
  store?: AtomicAssignmentHoldStore;
  /** Must be generated by a cryptographically secure source and unique across processes and restarts. */
  createOwner: () => string;
  isCurrent: () => boolean;
  /** Synchronous opaque account/scope/epoch snapshot, held only in memory. */
  scopeSnapshot: () => string | null;
  evaluator: AssignmentHoldEvaluator;
};

function current(options: Pick<HoldOptions, 'evaluator' | 'isCurrent' | 'scopeSnapshot'>, expected: string): boolean {
  return stringResult(options.evaluator, options.scopeSnapshot) === expected && trueResult(options.evaluator, options.isCurrent) &&
    stringResult(options.evaluator, options.scopeSnapshot) === expected;
}

/**
 * Unconnected safety prototype. It never clears an attempted write based on a
 * refresh, a 400, or an apparent success. A reviewed settlement protocol is
 * required before any attempted hold can be resolved or a route can use it.
 */
export class AssignmentWriteHold {
  constructor(private readonly options: HoldOptions) {}

  async acquire(): Promise<AssignmentWriteLease> {
    if (this.options.enabled !== true) throw denied('disabled');
    const store = this.options.store;
    if (!store) throw denied('storage_uncertain');
    const expected = stringResult(this.options.evaluator, this.options.scopeSnapshot);
    if (!expected || !current(this.options, expected)) throw denied('not_current');
    const owner = stringResult(this.options.evaluator, this.options.createOwner);
    // The shape can be checked, but randomness/uniqueness is a requirement on the caller.
    if (!owner || !/^[a-f0-9]{32,128}$/i.test(owner)) throw denied('invalid_owner');
    if (!current(this.options, expected)) throw denied('not_current');
    const marker: AssignmentWriteMarker = Object.freeze({ version: 1, owner });
    let acquired: boolean;
    try { acquired = await store.acquireIfAbsent(marker); }
    catch { throw denied('storage_uncertain'); }
    if (acquired === false) throw denied('busy');
    if (acquired !== true) throw denied('storage_uncertain');
    let observed: AssignmentWriteMarker | null;
    try { observed = await store.read(); }
    catch { throw denied('storage_uncertain'); }
    if (!observed || observed.version !== 1 || observed.owner !== owner) throw denied('ownership_uncertain');
    const lease = new AssignmentWriteLease(store, marker, this.options, expected);
    try {
      if (!current(this.options, expected)) throw denied('not_current');
    } catch (error) {
      // No send has been attempted. Conditional release cannot remove another owner.
      await lease.releaseIfUnsent();
      throw error;
    }
    return lease;
  }
}

class AssignmentWriteLease {
  private phase: 'reserved' | 'attempted' | 'releasing' | 'closed' | 'blocked' = 'reserved';
  constructor(private readonly store: AtomicAssignmentHoldStore, private readonly marker: AssignmentWriteMarker,
    private readonly options: Pick<HoldOptions, 'evaluator' | 'isCurrent' | 'scopeSnapshot'>, private readonly scope: string) {}

  /** Pass as the synchronous beforeSend guard only after acquisition and readback. */
  beforeSend = (): void => {
    if (this.phase !== 'reserved') throw denied('already_attempted');
    if (!current(this.options, this.scope)) throw denied('not_current');
    this.phase = 'attempted';
  };

  /** Only a definitely unsent reservation may be automatically released. */
  async releaseIfUnsent(): Promise<void> {
    if (this.phase !== 'reserved') throw denied('already_attempted');
    this.phase = 'releasing';
    try {
      if (await this.store.releaseIfOwner(this.marker.owner) !== true) {
        this.phase = 'blocked';
        throw denied('ownership_uncertain');
      }
      this.phase = 'closed';
    } catch (error) {
      this.phase = 'blocked';
      if (error instanceof AssignmentWriteHoldError) throw error;
      throw denied('storage_uncertain');
    }
  }
}
